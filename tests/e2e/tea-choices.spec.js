test('duplicate, failed and cancelled registration retain inputs; mobile registration and saving work offline', async ({ page, context }) => {
  const issues = diagnostics(page)
  await page.goto('./#/entries/new')
  await page.getByLabel('차 이름 *').fill('차구 등록 검수')
  await chooseOption(page, '사용한 차구', '자사호')
  await page.getByRole('button', { name: '내 차구 등록', exact: true }).click()
  const input = page.getByLabel('차구 이름 *', { exact: true })
  await input.fill('자사호')
  await page.getByRole('button', { name: '등록하고 선택', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toHaveText('이미 있는 이름입니다.')
  await expect(input).toHaveValue('자사호')
  await input.fill('저장 실패를 검수한 개완')
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'tools') {
        IDBObjectStore.prototype.put = original
        throw new DOMException('Test-only storage failure', 'QuotaExceededError')
      }
      return original.apply(this, args)
    }
  })
  await page.getByRole('button', { name: '등록하고 선택', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('입력 내용은 유지됩니다')
  await expect(input).toHaveValue('저장 실패를 검수한 개완')
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(page.getByLabel('차 이름 *')).toHaveValue('차구 등록 검수')
  await expect(page.getByRole('group', { name: '사용한 차구', exact: true }).getByRole('button', { name: '자사호', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const preserved = await backup(page)
  expect(preserved.data.entries).toEqual([])
  expect(preserved.data.tools.map((item) => item.name)).not.toContain('저장 실패를 검수한 개완')
  await nav(page, '새 기록')
  await page.getByRole('button', { name: '이어쓰기', exact: true }).click()
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
  await page.getByRole('button', { name: '이어쓰기', exact: true }).click()
  await context.setOffline(true)
  const longName = '오래기억할나의백자개완'.repeat(10).slice(0, 100)
  for (const width of [360, 390, 430]) {
    await page.setViewportSize({ width, height: 640 })
    await page.getByRole('button', { name: '내 차구 등록', exact: true }).click()
    await expect(input).toBeFocused()
    await input.fill(longName)
    const layout = await page.getByRole('dialog').evaluate((dialog) => {
      const box = dialog.getBoundingClientRect()
      return { left: box.left, right: box.right, width: innerWidth, overflow: dialog.scrollWidth > dialog.clientWidth, targets: [...dialog.querySelectorAll('button')].every((button) => button.getBoundingClientRect().height >= 44) }
    })
    expect(layout.left).toBeGreaterThanOrEqual(0)
    expect(layout.right).toBeLessThanOrEqual(width)
    expect(layout.overflow).toBe(false)
    expect(layout.targets).toBe(true)
    await page.screenshot({ path: `test-results/teaware-register-${width}.png` })
    await page.getByRole('button', { name: '취소', exact: true }).click()
  }
  await register(page, longName)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByText('초안 저장됨', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '이어쓰기', exact: true }).click()
  await expect(page.getByRole('group', { name: '사용한 차구', exact: true }).getByRole('button', { name: longName, exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '차구 등록 검수', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.detail-brew')).toContainText(longName)
  const final = await backup(page)
  expect(final.data.entries[0].brewing.tool).toBe(longName)
  expect(final.data.tools.filter((item) => item.name === longName)).toHaveLength(1)
  expect(issues).toEqual([])
})
