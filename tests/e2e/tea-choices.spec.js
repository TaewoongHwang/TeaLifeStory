import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { createEntry } from '../../src/utils/entry.js'
import { nav } from './helpers/navigation.js'
import { chooseOption, openDetails } from './helpers/entry-form.js'

const core = ['녹차', '홍차', '황차', '백차', '흑차']
function diagnostics(page) {
  const issues = []
  page.on('pageerror', (error) => issues.push(error.message))
  page.on('console', (message) => { if (['error', 'warning'].includes(message.type())) issues.push(message.text()) })
  return issues
}
async function backup(page) {
  await nav(page, '설정')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: '전체 데이터 내보내기', exact: true }).click()
  return JSON.parse(readFileSync(await (await pending).path(), 'utf8'))
}
async function restore(page, fixture, mode = 'replace') {
  await page.locator('#backup-file').setInputFiles({ name: 'choices.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture)) })
  if (mode === 'replace') await page.getByRole('radio', { name: /^전체 교체/ }).check()
  await page.getByRole('button', { name: mode === 'replace' ? '전체 교체하기' : '병합하기', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function register(page, name) {
  await openDetails(page)
  await page.getByRole('button', { name: '내 차구 등록', exact: true }).click()
  await page.getByLabel('차구 이름 *', { exact: true }).fill(name)
  await page.getByLabel('차구 이름 *', { exact: true }).press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/#\/entries\/new$/)
  await expect(page.getByRole('group', { name: '사용한 차구', exact: true }).getByRole('button', { name, exact: true })).toHaveAttribute('aria-pressed', 'true')
}

test('five core categories stay ordered; extra categories and the blending label preserve stored values', async ({ page }) => {
  const issues = diagnostics(page)
  await page.goto('./#/settings')
  const oldOptions = await backup(page)
  // Fixed entry choices remain available even if an old profile removed a default.
  oldOptions.data.categories = oldOptions.data.categories.filter((item) => item.name !== '황차')
  oldOptions.data.categories.push({ id: 'categories-6', name: '보이차' }, { id: 'category-matcha', name: '말차' })
  await restore(page, oldOptions)
  await nav(page, '새 기록')
  const group = page.getByRole('group', { name: '차 종류', exact: true })
  const primary = group.locator(':scope > .choice-buttons button')
  await expect(primary).toHaveText(core)
  await expect(group.getByRole('button', { name: '청차', exact: true })).toBeHidden()
  await group.locator('summary').click()
  for (const name of ['청차', '블렌딩티', '허브차', '기타', '말차']) await expect(group.getByRole('button', { name, exact: true })).toBeVisible()
  await expect(group.getByRole('button', { name: /보이차/ })).toHaveCount(0)
  await chooseOption(page, '차 종류', '블렌딩티')
  await chooseOption(page, '사용한 차구', '차관')
  await expect(primary).toHaveText(core)
  await page.getByLabel('차 이름 *').fill('블렌딩티 표시 확인')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '블렌딩티 표시 확인', exact: true })).toBeVisible()
  await expect(page.locator('.detail-brew')).toContainText('차관')
  const saved = await backup(page)
  expect(saved.data.entries[0].tea.category).toBe('블렌딩차')
  expect(saved.data.entries[0].brewing.tool).toBe('다관')
  expect(saved.data.tools.find((item) => item.id === 'tools-0').name).toBe('다관')
  const manager = page.locator('.option-manager').filter({ has: page.locator('#option-tools') })
  await manager.locator('summary').click()
  await manager.getByRole('button', { name: '차관 이름 수정', exact: true }).click()
  await expect(page.getByLabel('내 차구 수정할 이름', { exact: true })).toHaveValue('차관')
  await manager.getByRole('button', { name: '취소', exact: true }).click()
  expect((await backup(page)).data).toEqual(saved.data)
  await nav(page, '기록')
  await expect(page.locator('.entry-meta')).toContainText('차관')
  await nav(page, '설정')
  saved.data.categories.push({ id: 'custom-blending', name: '블렌딩티' })
  saved.data.tools.push({ id: 'custom-teapot', name: '차관' })
  await restore(page, saved)
  await nav(page, '새 기록')
  await group.locator('summary').click()
  await expect(group.getByRole('button', { name: '블렌딩티 (블렌딩차)', exact: true })).toBeVisible()
  await expect(group.getByRole('button', { name: '블렌딩티', exact: true })).toBeVisible()
  const tools = page.getByRole('group', { name: '사용한 차구', exact: true })
  await expect(tools.getByRole('button', { name: '차관 (기존 항목)', exact: true })).toBeVisible()
  await expect(tools.getByRole('button', { name: '차관', exact: true })).toBeVisible()
  expect(issues).toEqual([])
})

test('version 1 category IDs, photos and Boicha records and drafts survive merge and explicit recategorization', async ({ page }) => {
  const issues = diagnostics(page)
  await page.goto('./#/settings')
  const fixture = await backup(page)
  fixture.version = 1
  delete fixture.data.purchases
  fixture.data.categories = ['녹차', '백차', '황차', '청차', '홍차', '흑차', '보이차', '블렌딩차', '허브차', '기타'].map((name, index) => ({ id: `categories-${index}`, name }))
  const legacy = createEntry()
  Object.assign(legacy.tea, { name: '기존 보이차', category: '보이차' })
  legacy.brewing.tool = '옛 자사호'
  legacy.photos = [{ id: 'legacy-photo', name: '차.png', data: `data:image/png;base64,${readFileSync('public/icons/icon-192.png').toString('base64')}` }]
  const draft = structuredClone(legacy)
  draft.id = 'legacy-draft'
  draft.tea.name = '보이차 초안'
  fixture.data.entries = [legacy]
  fixture.data.settings = [{ key: 'draft', value: draft }]
  await restore(page, fixture, 'merge')
  const merged = await backup(page)
  expect(merged.version).toBe(2)
  expect(merged.data.categories).toEqual(expect.arrayContaining(fixture.data.categories))
  expect(merged.data.categories).toHaveLength(10)
  expect(merged.data.entries).toEqual([legacy])
  expect(merged.data.settings).toEqual(fixture.data.settings)
  await nav(page, '기록')
  await page.locator('.tea-card').click()
  await page.getByRole('link', { name: '기록 수정', exact: true }).click()
  const legacyButton = page.getByRole('group', { name: '차 종류', exact: true }).getByRole('button', { name: '보이차 (이전 기록)', exact: true })
  await expect(legacyButton).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '수정 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '기존 보이차', exact: true })).toBeVisible()
  const retained = (await backup(page)).data.entries[0]
  expect(retained.tea.category).toBe('보이차')
  expect(retained.photos).toEqual(legacy.photos)
  await nav(page, '새 기록')
  await page.getByRole('button', { name: '이어쓰기', exact: true }).click()
  await expect(legacyButton).toHaveAttribute('aria-pressed', 'true')
  await chooseOption(page, '차 종류', '흑차')
  await expect(legacyButton).toHaveCount(0)
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '보이차 초안', exact: true })).toBeVisible()
  await page.reload()
  const final = await backup(page)
  expect(final.data.entries.find((entry) => entry.id === legacy.id)).toEqual(retained)
  const resumed = final.data.entries.find((entry) => entry.tea.name === '보이차 초안')
  expect(resumed.tea.category).toBe('흑차')
  expect(resumed.photos).toEqual(legacy.photos)
  expect(final.data.settings).toEqual([])
  expect(issues).toEqual([])
})

